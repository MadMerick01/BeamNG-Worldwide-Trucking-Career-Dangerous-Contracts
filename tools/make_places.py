#!/usr/bin/env python3
"""Build the mod's place list from a GeoNames extract: thin it to well-known towns about 8 km
apart around a centre, and write a Lua table the mod loads. Built offline, never in game.

    python tools/make_places.py                  # rebuild placesData.lua from the bundled extract
    python tools/make_places.py --check          # fail if placesData.lua is out of date
    python tools/make_places.py --input cities1000.txt --radius-km 300

The input is GeoNames' tab-separated dump format (cities1000.txt, or a country file such as
AU.txt). tools/data/geonames_sydney.tsv is the Sydney region cut from cities1000. Place data is
(c) GeoNames, CC BY 4.0.
"""
import argparse
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / 'tools' / 'data' / 'geonames_sydney.tsv'
OVERRIDES = ROOT / 'tools' / 'data' / 'place_overrides.json'
OUTPUT = ROOT / 'mod' / 'earth_freight' / 'lua' / 'ge' / 'extensions' / 'earthFreight' / 'placesData.lua'
PENRITH = (-33.75, 150.7)
EARTH_RADIUS = 6371008.8
# Suburbs (GeoNames PPLX, a section of a populated place) rank below real towns of the same size,
# so the thinned list keeps Penrith and Katoomba ahead of the suburbs between them.
SUBURB_WEIGHT = 0.2
# Size classes by population; a place's size sets its arrival circle and its prices.
CITY_POPULATION, TOWN_POPULATION = 50000, 5000


def distance(a, b):
    lat1, lon1, lat2, lon2 = map(math.radians, (a[0], a[1], b[0], b[1]))
    h = math.sin((lat2 - lat1) / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin((lon2 - lon1) / 2) ** 2
    return 2 * EARTH_RADIUS * math.asin(min(1, math.sqrt(h)))


def read(path):
    places = []
    for line in path.read_text(encoding='utf-8').splitlines():
        cols = line.split('\t')
        if len(cols) < 15 or cols[6] != 'P':
            continue
        places.append({
            'geonameid': int(cols[0]), 'name': cols[1], 'lat': float(cols[4]), 'lon': float(cols[5]),
            'code': cols[7], 'population': int(cols[14] or 0),
        })
    return places


def build(places, overrides, centre, radius_km, spacing_km):
    include = set(overrides.get('include', []))
    exclude = set(overrides.get('exclude', []))
    near = [p for p in places if distance(centre, (p['lat'], p['lon'])) <= radius_km * 1000
            and p['name'] not in exclude and str(p['geonameid']) not in exclude]

    def score(p):
        forced = p['name'] in include or str(p['geonameid']) in include
        return (forced, p['population'] * (SUBURB_WEIGHT if p['code'] == 'PPLX' else 1), -p['geonameid'])

    kept = []
    for p in sorted(near, key=score, reverse=True):
        if all(distance((p['lat'], p['lon']), (k['lat'], k['lon'])) >= spacing_km * 1000 for k in kept):
            kept.append(p)
    missing = [name for name in include if not any(k['name'] == name or str(k['geonameid']) == name for k in kept)]
    if missing:
        raise SystemExit(f'Always-include places not kept (missing from the input or too close together): {missing}')
    return sorted(kept, key=lambda p: (p['name'], p['geonameid']))


def size(p):
    if p['population'] >= CITY_POPULATION:
        return 'city'
    return 'town' if p['population'] >= TOWN_POPULATION else 'village'


def lua(kept, centre, radius_km, spacing_km, source):
    def text(s):
        return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
    lines = [
        '-- Generated by tools/make_places.py; do not edit by hand. Rebuild with: python tools/make_places.py',
        '-- Place data (c) GeoNames (https://www.geonames.org/), CC BY 4.0.',
        'return {',
        f'  source = {text(source)},',
        f'  centre = {{ latitude = {centre[0]}, longitude = {centre[1]} }}, radiusKm = {radius_km}, spacingKm = {spacing_km},',
        '  places = {',
    ]
    for p in kept:
        lines.append(f'    {{ id = "gn{p["geonameid"]}", name = {text(p["name"])}, latitude = {p["lat"]:.5f}, '
                     f'longitude = {p["lon"]:.5f}, size = "{size(p)}", population = {p["population"]} }},')
    lines += ['  },', '}', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--input', type=Path, default=INPUT)
    parser.add_argument('--overrides', type=Path, default=OVERRIDES)
    parser.add_argument('--output', type=Path, default=OUTPUT)
    parser.add_argument('--centre', type=float, nargs=2, default=PENRITH, metavar=('LAT', 'LON'))
    parser.add_argument('--radius-km', type=float, default=150)
    parser.add_argument('--spacing-km', type=float, default=8)
    parser.add_argument('--check', action='store_true', help='fail if the output is out of date')
    args = parser.parse_args()
    overrides = json.loads(args.overrides.read_text(encoding='utf-8')) if args.overrides.exists() else {}
    kept = build(read(args.input), overrides, tuple(args.centre), args.radius_km, args.spacing_km)
    radius = int(args.radius_km) if args.radius_km == int(args.radius_km) else args.radius_km
    spacing = int(args.spacing_km) if args.spacing_km == int(args.spacing_km) else args.spacing_km
    out = lua(kept, tuple(args.centre), radius, spacing, args.input.name)
    if args.check:
        current = args.output.read_text(encoding='utf-8') if args.output.exists() else ''
        if current != out:
            print(f'{args.output} is out of date. Run: python tools/make_places.py', file=sys.stderr)
            return 1
        print(f'{args.output} is up to date ({len(kept)} places).')
        return 0
    args.output.write_text(out, encoding='utf-8', newline='\n')
    print(f'Wrote {len(kept)} places to {args.output}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
